// import_products.js
// Script to import products from products.json into src/data/products.js

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

// Resolve __dirname for ES module
const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const productsJsonPath = path.resolve(__dirname, '../../products.json');
const dataJsPath = path.resolve(__dirname, '../data/products.js');
const backupPath = dataJsPath + '.bak';

// Load JSON file
const jsonData = JSON.parse(fs.readFileSync(productsJsonPath, 'utf-8'));
const jsonProducts = jsonData.products || [];
const jsonCategories = jsonData.categories || [];

// Backup original data file
fs.copyFileSync(dataJsPath, backupPath);

// Load existing data module (it uses ES module syntax)
import { pathToFileURL } from 'url';
let existingModule;
try {
  existingModule = await import(pathToFileURL(dataJsPath).href);
} catch (e) {
  console.error('Failed to import existing data module:', e);
  process.exit(1);
}

const existingCategories = existingModule.CATEGORIES || [];
const existingProducts = existingModule.PRODUCTS || [];

// Helper to slugify category names matching existing format (lowercase, hyphens)
const slugify = (str) =>
  str
    .toLowerCase()
    .replace(/\s+/g, '-')
    .replace(/&/g, 'and')
    .replace(/[^a-z0-9-]/g, '');

// Build maps for duplicate checks
const existingSkus = new Set(existingProducts.map((p) => p.sku));
const existingSlugs = new Set(existingProducts.map((p) => p.slug));

let addedCount = 0;
let skippedCount = 0;
let missingImages = [];

// Add missing categories
jsonCategories.forEach((catName) => {
  const slug = slugify(catName);
  const exists = existingCategories.find((c) => c.slug === slug);
  if (!exists) {
    const newCat = {
      id: slug,
      name: catName,
      slug: slug,
      count: 0,
      image: 'https://via.placeholder.com/300?text=' + encodeURIComponent(catName),
    };
    existingCategories.push(newCat);
  }
});

// Map each JSON product to the format used in PRODUCTS array
jsonProducts.forEach((p) => {
  if (existingSkus.has(p.sku) || existingSlugs.has(p.slug)) {
    skippedCount++;
    return;
  }
  // Build product object
  const prod = {
    id: p.id || p.sku,
    sku: p.sku,
    slug: p.slug,
    name: p.name,
    tagline: p.description?.substring(0, 80) || '',
    category: slugify(p.category),
    subcategory: p.subcategory || '',
    price: p.price,
    compareAtPrice: p.sale_price || null,
    badge: p.featured ? 'FEATURED' : p.new_arrival ? 'NEW' : null,
    rating: p.rating,
    reviewCount: p.reviews_count,
    isNew: !!p.new_arrival,
    isBestseller: false,
    isFeatured: !!p.featured,
    occasions: (p.occasion || []).map(slugify),
    material: p.material,
    color: p.color,
    gemstone: p.gemstone,
    stock: p.stock,
    description: p.description,
    tags: p.tags || [],
    images: (p.images || []).map((img) => {
      // Verify if image exists in public folder
      const publicPath = path.resolve(__dirname, '../../public', img);
      if (!fs.existsSync(publicPath)) {
        missingImages.push(img);
      }
      return img;
    }),
    created_at: p.created_at,
  };
  existingProducts.push(prod);
  addedCount++;
});

// Generate new file content
const generateFile = () => {
  const header = `/**
 * Minha Jewellers - Product Catalog (auto‑generated by import script)
 */\n\n`;
  const categoriesStr = `export const CATEGORIES = ${JSON.stringify(existingCategories, null, 2)};\n\n`;
  const occasionsStr = `export const OCCASIONS = ${JSON.stringify(existingModule.OCCASIONS, null, 2)};\n\n`;
  const productsStr = `export const PRODUCTS = ${JSON.stringify(existingProducts, null, 2)};\n`;
  return header + categoriesStr + occasionsStr + productsStr;
};

fs.writeFileSync(dataJsPath, generateFile(), 'utf-8');

console.log('Import complete.');
console.log('Added:', addedCount, 'Skipped (duplicates):', skippedCount);
if (missingImages.length) {
  console.log('Missing image files (will show placeholder):', missingImages.length);
}
